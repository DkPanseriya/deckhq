#!/usr/bin/env node
/**
 * Compile `DeckHQ.exe` with the C# compiler that is part of Windows.
 *
 *   node app/windows/build-shell.mjs      # dist/app/_build/shell/DeckHQ.exe
 *
 * There is no SDK, no project file and no NuGet restore here. The .NET
 * Framework 4.x that every supported Windows carries includes `csc.exe`, and
 * that is the whole toolchain: it is on the maintainer's machine and on
 * GitHub's `windows-latest` runner alike. It speaks C# 5, which is why the
 * sources in `shell/` are written the way they are.
 *
 * The icon is not drawn here either. `public/icon-*.png` are the mark at six
 * sizes (`scripts/brand/render-icons.mjs`); `makeIcon` wraps them in an ICO
 * with the package's own `src/core/ico.mjs`, byte for byte.
 */
import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

import { pngToIco } from '../../src/core/ico.mjs';
import { REPO, WEBVIEW2_DIR } from './fetch-webview2.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));

export const SHELL_SRC = path.join(HERE, 'shell');
export const BUILD_DIR = path.join(REPO, 'dist', 'app', '_build');
export const SHELL_EXE = path.join(BUILD_DIR, 'shell', 'DeckHQ.exe');
export const ICON_FILE = path.join(BUILD_DIR, 'DeckHQ.ico');

/** The sizes Windows asks an application icon for, title bar to Start Menu tile. */
export const ICON_SIZES = [16, 32, 48, 64, 128, 256];

export const PUBLISHER = 'Darshak Panseriya';

/** The mark as one multi-size ICO, from the PNGs the package already ships. */
export function makeIcon() {
  return pngToIco(
    ICON_SIZES.map((size) => fs.readFileSync(path.join(REPO, 'public', `icon-${size}.png`))),
  );
}

/** The Framework's own compiler, 64-bit first. Null when this is not Windows. */
export function findCsc(env = process.env) {
  const windir = env.WINDIR || env.SystemRoot || 'C:\\Windows';
  for (const flavour of ['Framework64', 'Framework']) {
    const csc = path.join(windir, 'Microsoft.NET', flavour, 'v4.0.30319', 'csc.exe');
    if (fs.existsSync(csc)) return csc;
  }
  return null;
}

/** `1.7.1` → `1.7.1.0`: a Win32 version resource has four numbers. */
export function fourPartVersion(version) {
  const parts = String(version).split(/[.+-]/).slice(0, 3);
  return [...parts.map((p) => String(Number(p) || 0)), '0'].join('.');
}

/** @param {string} version */
export function assemblyInfo(version) {
  const four = fourPartVersion(version);
  return [
    '// Generated by app/windows/build-shell.mjs from package.json. Not edited by hand.',
    'using System.Reflection;',
    '[assembly: AssemblyTitle("DeckHQ")]',
    '[assembly: AssemblyProduct("DeckHQ")]',
    '[assembly: AssemblyDescription("An office for your AI coding agents")]',
    `[assembly: AssemblyCompany("${PUBLISHER}")]`,
    `[assembly: AssemblyCopyright("MIT License. Copyright (c) ${PUBLISHER}")]`,
    `[assembly: AssemblyVersion("${four}")]`,
    `[assembly: AssemblyFileVersion("${four}")]`,
    `[assembly: AssemblyInformationalVersion("${version}")]`,
    '',
  ].join('\r\n');
}

/**
 * The compiler's argv. Pure, so the test can hold it to "no network assembly
 * is referenced" without compiling anything.
 * @param {{out:string, icon:string, info:string, webview2:string, sources:string[]}} o
 */
export function cscArgs(o) {
  return [
    '/nologo',
    '/target:winexe',
    '/platform:anycpu',
    '/langversion:5',
    '/optimize+',
    '/debug-',
    '/warn:4',
    `/out:${o.out}`,
    `/win32icon:${o.icon}`,
    `/win32manifest:${path.join(SHELL_SRC, 'app.manifest')}`,
    `/resource:${o.icon},DeckHQ.ico`,
    '/r:System.dll',
    '/r:System.Core.dll',
    '/r:System.Drawing.dll',
    '/r:System.Windows.Forms.dll',
    `/r:${path.join(o.webview2, 'Microsoft.Web.WebView2.Core.dll')}`,
    `/r:${path.join(o.webview2, 'Microsoft.Web.WebView2.WinForms.dll')}`,
    o.info,
    ...o.sources,
  ];
}

/** Every C# file of the shell, in a stable order. */
export function shellSources() {
  return fs
    .readdirSync(SHELL_SRC)
    .filter((name) => name.endsWith('.cs'))
    .sort()
    .map((name) => path.join(SHELL_SRC, name));
}

/** @param {{version?:string, log?:(line:string) => void}} [opts] */
export function buildShell(opts = {}) {
  const log = opts.log || ((line) => process.stdout.write(`${line}\n`));
  const version =
    opts.version || JSON.parse(fs.readFileSync(path.join(REPO, 'package.json'), 'utf8')).version;
  const csc = findCsc();
  if (!csc)
    throw new Error('csc.exe was not found under %WINDIR%\\Microsoft.NET; this builds on Windows');
  if (!fs.existsSync(path.join(WEBVIEW2_DIR, 'Microsoft.Web.WebView2.Core.dll'))) {
    throw new Error('the WebView2 SDK is not here yet: run `node app/windows/fetch-webview2.mjs`');
  }
  fs.mkdirSync(path.dirname(SHELL_EXE), { recursive: true });
  fs.writeFileSync(ICON_FILE, makeIcon());
  const info = path.join(BUILD_DIR, 'shell', 'AssemblyInfo.cs');
  fs.writeFileSync(info, assemblyInfo(version), 'utf8');

  const args = cscArgs({
    out: SHELL_EXE,
    icon: ICON_FILE,
    info,
    webview2: WEBVIEW2_DIR,
    sources: shellSources(),
  });
  log(`csc  ${csc}`);
  const out = execFileSync(csc, args, { encoding: 'utf8', windowsHide: true });
  if (out.trim()) log(out.trim());
  log(`  ${SHELL_EXE}  ${fs.statSync(SHELL_EXE).size} bytes`);
  return SHELL_EXE;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    buildShell();
  } catch (err) {
    process.stderr.write(`\n  build-shell: ${err?.stdout || ''}${err?.message || err}\n\n`);
    process.exitCode = 1;
  }
}
