/**
 * The installer's file list and the uninstaller's, from one folder listing.
 *
 * `installer.nsi` could say `File /r` and its uninstaller `RMDir /r $INSTDIR`,
 * and that pair is how an uninstaller comes to delete things it never wrote:
 * whatever the user, or anything else, put in that folder goes with it. So
 * the two lists are generated instead. Every file the app folder holds is
 * installed by name and removed by name, and a directory is removed only once
 * it is empty (`RMDir` without `/r`), deepest first.
 *
 * Pure: a list of relative paths in, two strings out.
 */

/** A path as NSIS wants it inside a double-quoted string. */
function nsis(rel) {
  return rel.replace(/\//g, '\\').replace(/\$/g, '$$$$');
}

/** `a/b/c.txt` → `a/b`; a file at the top → ``. */
function dirOf(rel) {
  const at = rel.lastIndexOf('/');
  return at === -1 ? '' : rel.slice(0, at);
}

/**
 * @param {string[]} files paths relative to the app folder, forward slashes
 * @returns {{install:string, uninstall:string, dirs:string[]}}
 */
export function nsisFileLists(files) {
  const sorted = [...new Set(files)].sort();
  for (const rel of sorted) {
    if (/^([a-z]:|[\\/])|(^|\/)\.\.(\/|$)|["\r\n]/i.test(rel)) {
      throw new Error(`refusing to list ${JSON.stringify(rel)}: not a plain relative path`);
    }
  }

  /** @type {Map<string, string[]>} */
  const byDir = new Map();
  for (const rel of sorted) {
    const dir = dirOf(rel);
    if (!byDir.has(dir)) byDir.set(dir, []);
    byDir.get(dir).push(rel);
  }

  const install = ['; Generated by app/windows/build.mjs. Not edited by hand.'];
  for (const [dir, names] of [...byDir].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    install.push(`SetOutPath "$INSTDIR${dir ? `\\${nsis(dir)}` : ''}"`);
    for (const rel of names) install.push(`File "\${APP_SRC}\\${nsis(rel)}"`);
  }

  // Every directory any file sits in, and every parent of one.
  const dirs = new Set();
  for (const dir of byDir.keys()) {
    for (let d = dir; d; d = dirOf(d)) dirs.add(d);
  }
  const deepestFirst = [...dirs].sort(
    (a, b) => b.split('/').length - a.split('/').length || (a < b ? -1 : 1),
  );

  const uninstall = ['; Generated by app/windows/build.mjs. Not edited by hand.'];
  for (const rel of sorted) uninstall.push(`Delete "$INSTDIR\\${nsis(rel)}"`);
  for (const dir of deepestFirst) uninstall.push(`RMDir "$INSTDIR\\${nsis(dir)}"`);

  return {
    install: `${install.join('\r\n')}\r\n`,
    uninstall: `${uninstall.join('\r\n')}\r\n`,
    dirs: deepestFirst,
  };
}
